// Writes the compiled GiftRegistry ABI to ../lib/giftRegistryAbi.ts for the frontend.
import { readFileSync, writeFileSync } from "node:fs";

const artifact = JSON.parse(readFileSync("artifacts/contracts/GiftRegistry.sol/GiftRegistry.json", "utf8"));
writeFileSync(
  "../lib/giftRegistryAbi.ts",
  `// Generated by contracts/scripts/export-abi.mjs - do not edit.\nexport const giftRegistryAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`,
);
console.log("Wrote lib/giftRegistryAbi.ts");
